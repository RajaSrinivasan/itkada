#!/usr/bin/env bash
# Configure a tiny CMake probe against ITK and write itk_paths.gpr.
# Honors ITK_DIR and CMAKE_PREFIX_PATH. ITK must be >= 5.4.8 and provide
# the modules listed in tools/itk_modules.txt.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD="${ROOT}/obj/itk_paths"
OUT="${ROOT}/itk_paths.gpr"
CXX="${ITKLIB_CXX:-${CXX:-g++}}"

if [[ -z "${ITK_DIR:-}" && -n "${ITK_PREFIX:-}" ]]; then
  for candidate in "${ITK_PREFIX}"/lib/cmake/ITK-*; do
    if [[ -f "${candidate}/ITKConfig.cmake" ]]; then
      ITK_DIR="${candidate}"
      break
    fi
  done
fi
if [[ -z "${ITK_DIR:-}" && -f /opt/itk-5.4.8/lib/cmake/ITK-5.4/ITKConfig.cmake ]]; then
  ITK_DIR="/opt/itk-5.4.8/lib/cmake/ITK-5.4"
fi
export ITK_DIR

cmake -S "${ROOT}/tools/itk_paths" -B "${BUILD}" -G "Unix Makefiles" \
  -DCMAKE_CXX_COMPILER="${CXX}" >/tmp/itklib-itk-paths-cmake.log

python3 - "${BUILD}" "${OUT}" "${CXX}" << 'PY'
import pathlib, shlex, sys

build = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])
cxx = sys.argv[3]

def uncontinued(path):
    return path.read_text().replace("\\\n", " ")

meta = {}
for line in (build / "itk_meta.txt").read_text().splitlines():
    if "=" in line:
        key, value = line.split("=", 1)
        meta[key] = value

flags = {}
for line in uncontinued(build / "CMakeFiles" / "probe.dir" / "flags.make").splitlines():
    if line.startswith("#") or " = " not in line:
        continue
    key, value = line.split(" = ", 1)
    flags[key.strip()] = value.strip()

includes = []
inc_tokens = shlex.split(flags.get("CXX_INCLUDES", ""))
index = 0
while index < len(inc_tokens):
    token = inc_tokens[index]
    if token in ("-I", "-isystem", "-idirafter") and index + 1 < len(inc_tokens):
        path = inc_tokens[index + 1]
        index += 2
        if "ITKFactoryRegistration" in path:
            continue
        includes.append(token)
        includes.append(path)
        continue
    if token.startswith("-I") or token.startswith("-isystem"):
        index += 1
        if "ITKFactoryRegistration" in token:
            continue
        includes.append(token)
        continue
    index += 1
if not includes:
    raise SystemExit("ITK include directories were not discovered")

defines = []
skip = ("FACTORY_REGISTER_MANAGER", "EXPORTS")
for token in shlex.split(flags.get("CXX_DEFINES", "")):
    if not token.startswith("-D"):
        continue
    if any(marker in token for marker in skip):
        continue
    defines.append(token)
for token in shlex.split(flags.get("CXX_FLAGS", "")):
    if token in ("-fPIC", "-fPIE", "-g") or token.startswith(("-std=", "-O")):
        continue
    if token.startswith("-"):
        defines.append(token)
if not defines:
    defines = ["-DITKLIB_NO_EXTRA_DEFINES=1"]

link_text = uncontinued(build / "CMakeFiles" / "probe.dir" / "link.txt")
tokens = shlex.split(link_text)
link = []
skip_next = False
for token in tokens:
    if skip_next:
        skip_next = False
        continue
    if token == "-o":
        skip_next = True
        continue
    if token in ("-shared", "-fPIC", "-rdynamic"):
        continue
    if token.startswith("-Wl,-soname"):
        continue
    if token.endswith((".o", ".obj", ".cpp", ".cxx")):
        continue
    if token.startswith(("-L", "-l", "-Wl,", "-pthread")) or token == "-pthread":
        link.append(token)
        continue
    if token.startswith("/") and (".so" in token or token.endswith(".a")):
        link.append(token)

import subprocess
printed = subprocess.check_output(
    [cxx, "-print-file-name=libstdc++.so"], text=True
).strip()
if printed and printed != "libstdc++.so":
    libdir = str(pathlib.Path(printed).resolve().parent)
    rpath = f"-Wl,-rpath,{libdir}"
    if rpath not in link:
        link.append(rpath)

lib_dir = ""
for token in link:
    if token.startswith("/") and "libITKCommon" in token:
        lib_dir = str(pathlib.Path(token).parent)
        break
if not lib_dir:
    for token in link:
        if token.startswith("-Wl,-rpath,") and "rpath-link" not in token:
            lib_dir = token.split(",", 2)[-1]
            break
if lib_dir:
    rpath = f"-Wl,-rpath,{lib_dir}"
    if rpath not in link:
        link.insert(0, rpath)

def gpr_list(items):
    quoted = ",\n      ".join(f'"{item}"' for item in items)
    return "(\n      " + quoted + ")"

version = meta.get("version", "unknown")
text = f"""--  Generated by tools/generate_itk_paths.sh. Do not edit.
abstract project Itk_Paths is
   ITK_Version := "{version}";
   ITK_Lib_Dir := "{lib_dir}";
   Include_Switches := {gpr_list(includes)};
   Cxx_Switches := {gpr_list(defines)};
   Link_Switches := {gpr_list(link)};
end Itk_Paths;
"""
out.write_text(text)
print(f"Wrote {out} for ITK {version}")
PY
