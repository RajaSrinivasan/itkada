def render_instances(pixel: dict, spec: dict, filters: list[dict], matrix: dict, pixels: dict) -> str:
    lines = [
        f"--  {MARKER}. Do not edit.",
        "with Itklib.Images;",
        f"with Itklib.Pixels.{spec['ada_kind']};",
    ]
    packages = []
    for filt in filters:
        if not category_allows(filt, spec) or not pixel_allowed(filt, pixel):
            continue
        dims = [dim for dim in matrix["dimensions"] if dim in filt.get("dimensions", [2, 3])]
        if not dims:
            continue
        if filt["ada_package"] not in packages:
            lines.append(f"with {filt['ada_package']};")
            packages.append(filt["ada_package"])
    lines.append("")
    lines.append(f"package Itklib.Instances.{spec['ada_kind']} with SPARK_Mode => Off is")
    for dim in matrix["dimensions"]:
        lines.append(
            f"   package Image_{dim}D is new Itklib.Images (Itklib.Pixels.{spec['ada_kind']}, {dim});"
        )
    for filt in filters:
        if filt.get("output") == "cast":
            continue
        if not category_allows(filt, spec) or not pixel_allowed(filt, pixel):
            continue
        for dim in matrix["dimensions"]:
            if dim not in filt.get("dimensions", [2, 3]):
                continue
            formal = filt.get("formal", "pair")
            if formal == "single":
                lines.append(
                    f"   package {filt['name']}_{dim}D is new {filt['ada_package']} (Image_{dim}D);"
                )
            else:
                lines.append(
                    f"   package {filt['name']}_{dim}D is new {filt['ada_package']} (Image_{dim}D, Image_{dim}D);"
                )
    if any(filt.get("output") == "cast" and category_allows(filt, spec) for filt in filters):
        for filt in filters:
            if filt.get("output") != "cast":
                continue
            for dim in matrix["dimensions"]:
                if dim not in filt.get("dimensions", [2, 3]):
                    continue
                lines.append(
                    f"   package {filt['name']}_{dim}D is new {filt['ada_package']} (Image_{dim}D, Image_{dim}D);"
                )
    lines.append(f"end Itklib.Instances.{spec['ada_kind']};")
    lines.append("")
    return "\n".join(lines)


