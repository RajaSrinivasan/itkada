def snake_case(name: str) -> str:
    out: list[str] = []
    for index, char in enumerate(name):
        if char.isupper() and index and name[index - 1].islower():
            out.append("_")
        out.append(char.lower())
    return "".join(out)


def load_yaml(path: Path):
    return yaml.safe_load(path.read_text())


def pixel_db(root: Path = ROOT) -> dict[str, dict]:
    data = load_yaml(root / "tools" / "pixel_types.yaml")
    return {item["name"]: item for item in data["pixels"]}


def load_matrix(root: Path = ROOT) -> dict:
    data = load_yaml(root / "tools" / "matrix.yaml")
    pixels = []
    limits = data.get("filters") or {}
    for item in data["pixels"]:
        if isinstance(item, str):
            pixels.append({"name": item, "filters": None})
        else:
            pixels.append(
                {"name": item["name"], "filters": item.get("filters")}
            )
    for name, allowed in limits.items():
        for pixel in pixels:
            if pixel["name"] == name and pixel["filters"] is None:
                pixel["filters"] = list(allowed)
    return {"dimensions": [int(d) for d in data["dimensions"]], "pixels": pixels}


def load_filters(root: Path = ROOT) -> list[dict]:
    filters = []
    for path in sorted((root / "tools" / "filters").glob("*.yaml")):
        item = load_yaml(path)
        item["_path"] = path.name
        item.setdefault("members", [])
        item.setdefault("dimensions", [2, 3])
        item.setdefault("pixel_category", "scalar")
        item.setdefault("output", "same")
        item.setdefault("formal", "pair")
        item.setdefault("generate_sources", True)
        item.setdefault("itk_arity", 1 if item.get("output") == "none" else int(item.get("itk_arity", 2)))
        item.setdefault("kernel", "flat" if item.get("structuring_element") == "ball" else "none")
        filters.append(item)
    filters.sort(key=lambda item: int(item["id"]))
    return filters


def write_matrix(matrix: dict, root: Path = ROOT) -> None:
    lines = [
        "# Default pre-built instantiations. UInt16 in 2D and 3D ships in the crate.",
        "# tools/add_pixel_type.py appends other pixels; it does not edit this comment.",
        "dimensions: [" + ", ".join(str(d) for d in matrix["dimensions"]) + "]",
        "pixels:",
    ]
    for pixel in matrix["pixels"]:
        lines.append(f"  - {pixel['name']}")
    limited = [pixel for pixel in matrix["pixels"] if pixel.get("filters")]
    if limited:
        lines.append("filters:")
        for pixel in limited:
            joined = ", ".join(pixel["filters"])
            lines.append(f"  {pixel['name']}: [{joined}]")
    text = "\n".join(lines) + "\n"
    (root / "tools" / "matrix.yaml").write_text(text)


def category_allows(filt: dict, spec: dict) -> bool:
    category = filt.get("pixel_category", "scalar")
    if category == "scalar":
        return spec["category"] in ("integer", "real")
    if category == "real_only":
        return spec["category"] == "real"
    if category == "integer":
        return spec["category"] == "integer"
    raise SystemExit(f"{filt['name']}: unknown pixel_category {category}")


def pixel_allowed(filt: dict, pixel: dict) -> bool:
    if filt.get("pixels") and pixel["name"] not in filt["pixels"]:
        return False
    if pixel.get("filters") and filt["name"] not in pixel["filters"]:
        return False
    return True


def instantiations(filt: dict, matrix: dict, pixels: dict[str, dict]) -> list[tuple[str, int]]:
    """(ada kind, dimension) pairs this filter is built for."""
    found = []
    dims = [int(d) for d in filt.get("dimensions", [2, 3])]
    for pixel in matrix["pixels"]:
        spec = pixels[pixel["name"]]
        if not category_allows(filt, spec) or not pixel_allowed(filt, pixel):
            continue
        for dim in matrix["dimensions"]:
            if dim in dims:
                found.append((spec["ada_kind"], dim))
    return found


def skip_reasons(pixel_name: str, dims: list[int], filters: list[dict], pixels: dict, matrix: dict) -> list[str]:
    spec = pixels[pixel_name]
    notes = []
    if not spec.get("png", False):
        notes.append(
            f"skip PNG writer for {pixel_name}: {spec.get('png_skip', 'PNG cannot store this pixel')}"
        )
    dummy = {"name": pixel_name, "filters": None}
    for filt in filters:
        if filt.get("pixels") and pixel_name not in filt["pixels"]:
            reason = filt.get("manual_reason", "not in this filter's pixel list")
            notes.append(f"skip {filt['name']} for {pixel_name}: {reason}")
            continue
        if not category_allows(filt, spec):
            notes.append(
                f"skip {filt['name']} for {pixel_name}: pixel_category {filt.get('pixel_category')} "
                f"does not include {spec['category']}"
            )
            continue
        missing = [dim for dim in dims if dim not in filt.get("dimensions", [2, 3])]
        if missing:
            notes.append(
                f"skip {filt['name']} for {pixel_name} dimensions {missing}: filter dimensions are {filt.get('dimensions')}"
            )
    return notes


def validate_addition(pixel_name: str, dims: list[int], pixels: dict) -> None:
    if pixel_name in REJECTED:
        raise SystemExit(f"refusing {pixel_name}: {REJECTED[pixel_name]}")
    if pixel_name not in pixels:
        known = ", ".join(sorted(pixels))
        raise SystemExit(f"unknown pixel {pixel_name}. Known scalars: {known}")
    if not dims:
        raise SystemExit("at least one dimension is required")
    bad = [dim for dim in dims if dim not in (2, 3, 4)]
    if bad:
        raise SystemExit(f"dimensions must be in {{2, 3, 4}}, got {bad}")


def _cxx_body(kind: str, itk: str, where: str, clear_first: bool) -> str:
    null = (
        f'if (values == nullptr) {{ throw itklib_status{{ITKLIB_E_NULL, "null values", "{where}"}}; }}'
    )
    if kind == "bool":
        return f"concrete->{itk}(enabled != 0);"
    if kind == "double":
        return f"concrete->{itk}(value);"
    if kind == "unsigned":
        return f"concrete->{itk}(static_cast<unsigned int>(value));"
    if kind == "pixel":
        return f'concrete->{itk}(itklib_from_double<Pixel>(value, "{where}"));'
    if kind == "double_vector":
        return (
            f"{null} itk::FixedArray<double, Dimension> array; "
            "for (unsigned axis = 0; axis < Dimension; ++axis) { array[axis] = values[axis]; } "
            f"concrete->{itk}(array);"
        )
    if kind in ("radius", "ball_radius"):
        assign = (
            f"{null} for (unsigned axis = 0; axis < Dimension; ++axis) {{ "
            "if (values[axis] > std::numeric_limits<itk::SizeValueType>::max()) { "
            f'throw itklib_status{{ITKLIB_E_ARG, "radius is too large", "{where}"}}; }} '
        )
        if kind == "ball_radius":
            return (
                assign
                + " } { using Kernel = typename std::remove_reference_t<decltype(*concrete)>::KernelType; "
                "typename Kernel::RadiusType radius; "
                "for (unsigned axis = 0; axis < Dimension; ++axis) { "
                "radius[axis] = static_cast<itk::SizeValueType>(values[axis]); } "
                "concrete->SetKernel(Kernel::Ball(radius)); }"
            )
        return (
            assign
            + "} { using Radius_Type = typename std::remove_reference_t<decltype(*concrete)>::RadiusType; "
            "Radius_Type radius; "
            "for (unsigned axis = 0; axis < Dimension; ++axis) { "
            "radius[axis] = static_cast<itk::SizeValueType>(values[axis]); } "
            f"concrete->{itk}(radius); }}"
        )
    if kind == "factors":
        return (
            f"{null} itk::FixedArray<unsigned int, Dimension> factors; "
            "for (unsigned axis = 0; axis < Dimension; ++axis) { "
            "if (values[axis] == 0 || values[axis] > std::numeric_limits<unsigned int>::max()) { "
            f'throw itklib_status{{ITKLIB_E_ARG, "factor must be a positive int", "{where}"}}; }} '
            "factors[axis] = static_cast<unsigned int>(values[axis]); } "
            f"concrete->{itk}(factors);"
        )
    if kind == "seed":
        clear = "concrete->ClearSeeds(); " if clear_first else ""
        return (
            f"{null} typename itk::Image<Pixel, Dimension>::IndexType index; "
            "for (unsigned axis = 0; axis < Dimension; ++axis) { "
            "index[axis] = static_cast<itk::IndexValueType>(values[axis]); } "
            f"{clear}concrete->{itk}(index);"
        )
    if kind == "getter_double":
        return ""
    raise SystemExit(f"unknown member kind {kind}")


def prepare_filter(filt: dict) -> dict:
    prepared = dict(filt)
    prepared["snake"] = snake_case(filt["name"])
    prepared["c_prefix"] = "itklib_" + prepared["snake"]
    prepared["ns"] = "itklib_gen_" + prepared["snake"]
    prepared["yaml_name"] = filt["_path"]
    category = filt.get("pixel_category", "scalar")
    if filt.get("output") == "cast":
        prepared["visitor"] = "itklib_visit_pair"
    elif category == "real_only":
        prepared["visitor"] = "itklib_visit_real"
    elif category == "integer":
        prepared["visitor"] = "itklib_visit_integer"
    else:
        prepared["visitor"] = "itklib_visit_builtin"
    image_pkg = "Img" if filt.get("formal") == "single" else "Input"
    prepared["image_pkg"] = image_pkg
    prepared["output_pkg"] = "Img" if filt.get("formal") == "single" else "Output"
    members = []
    for member in filt.get("members") or []:
        item = dict(member)
        item["snake"] = snake_case(member["ada"])
        where = f"{prepared['c_prefix']}_{item['snake']}"
        kind = member["kind"]
        item["cxx_body"] = _cxx_body(kind, member["itk"], where, bool(member.get("clear_first")))
        if kind == "bool":
            item["c_params"] = ", int enabled"
            item["cxx_params"] = ", int enabled"
            item["call_args"] = ", enabled"
        elif kind in ("double", "pixel"):
            item["c_params"] = ", double value"
            item["cxx_params"] = ", double value"
            item["call_args"] = ", value"
        elif kind == "unsigned":
            item["c_params"] = ", unsigned value"
            item["cxx_params"] = ", unsigned value"
            item["call_args"] = ", value"
        elif kind == "getter_double":
            item["c_params"] = ", double * value"
            item["cxx_params"] = ""
            item["call_args"] = ""
        elif kind == "double_vector":
            item["c_params"] = ", const double * values"
            item["cxx_params"] = ", const double * values"
            item["call_args"] = ", values"
        elif kind == "seed":
            item["c_params"] = ", const int64_t * values"
            item["cxx_params"] = ", const int64_t * values"
            item["call_args"] = ", values"
        else:
            item["c_params"] = ", const uint64_t * values"
            item["cxx_params"] = ", const uint64_t * values"
            item["call_args"] = ", values"
        members.append(item)
    prepared["members"] = members
    prepared["needs_radius_type"] = any(m["kind"] in ("radius", "ball_radius") for m in members)
    prepared["needs_factors_type"] = any(m["kind"] == "factors" for m in members)
    prepared["brief"] = " ".join((filt.get("brief") or filt["name"]).split())
    if "klass" not in prepared:
        prepared["klass"] = "ITKLIB_CLASS_" + prepared["snake"].upper()
    return prepared


def _predicate(pairs: list[tuple[str, int]], *, cast: bool = False) -> str:
    if cast:
        return ""
    if not pairs:
        return "(False and then Kind in Itklib.Pixel_Kind and then Dimension > 0)"
    grouped: dict[str, list[int]] = {}
    for kind, dim in pairs:
        grouped.setdefault(kind, []).append(dim)
    lines = ["(case Kind is"]
    for kind in sorted(grouped):
        dims = " or else ".join(f"Dimension = {dim}" for dim in sorted(set(grouped[kind])))
        lines.append(f"            when Itklib.{kind} => {dims},")
    lines.append("            when others => False)")
    return "\n".join(lines)


def _visit_function(name: str, entries: list[tuple[str, int, str]], pair: bool = False) -> str:
    if pair:
        if not entries:
            return (
                f"template <typename Visitor>\nvoid\n{name} (itklib_pixel_id, itklib_pixel_id, unsigned, Visitor &&)\n"
                "{\n  throw itklib_status{ITKLIB_E_UNSUPPORTED,\n"
                '                      "pixel/dimension is not built in this itklib",\n'
                f'                      "{name}"}};\n}}\n'
            )
        lines = [
            "template <typename Visitor>",
            "void",
            f"{name} (itklib_pixel_id input, itklib_pixel_id output, unsigned dimension, Visitor && visitor)",
            "{",
        ]
        for in_cxx, out_cxx, dim, in_id, out_id in entries:
            lines.append(
                f"  if (input == {in_id} && output == {out_id} && dimension == {dim})\n"
                "    {\n"
                f"      visitor (Itklib_Type<{in_cxx}>{{}}, Itklib_Type<{out_cxx}>{{}}, Itklib_Dim<{dim}>{{}});\n"
                "      return;\n"
                "    }"
            )
        lines.append(
            "  throw itklib_status{ITKLIB_E_UNSUPPORTED,\n"
            '                      "pixel/dimension is not built in this itklib",\n'
            f'                      "{name}"}};\n}}\n'
        )
        return "\n".join(lines)
    if not entries:
        return (
            f"template <typename Visitor>\nvoid\n{name} (itklib_pixel_id, unsigned, Visitor &&)\n"
            "{\n  throw itklib_status{ITKLIB_E_UNSUPPORTED,\n"
            '                      "pixel/dimension is not built in this itklib",\n'
            f'                      "{name}"}};\n}}\n'
        )
    lines = [
        "template <typename Visitor>",
        "void",
        f"{name} (itklib_pixel_id pixel, unsigned dimension, Visitor && visitor)",
        "{",
    ]
    for cxx, dim, enum_id in entries:
        lines.append(
            f"  if (pixel == {enum_id} && dimension == {dim})\n"
            "    {\n"
            f"      visitor (Itklib_Type<{cxx}>{{}}, Itklib_Dim<{dim}>{{}});\n"
            "      return;\n"
            "    }"
        )
    lines.append(
        "  throw itklib_status{ITKLIB_E_UNSUPPORTED,\n"
        '                      "pixel/dimension is not built in this itklib",\n'
        f'                      "{name}"}};\n}}\n'
    )
    return "\n".join(lines)


def _enum_id(spec: dict) -> str:
    return {
        1: "ITKLIB_UINT8",
        2: "ITKLIB_INT8",
        3: "ITKLIB_UINT16",
        4: "ITKLIB_INT16",
        5: "ITKLIB_UINT32",
        6: "ITKLIB_INT32",
        7: "ITKLIB_UINT64",
        8: "ITKLIB_INT64",
        9: "ITKLIB_FLOAT32",
        10: "ITKLIB_FLOAT64",
    }[int(spec["id"])]


def builtin_entries(matrix: dict, pixels: dict, *, category: str | None = None, png: bool = False):
    entries = []
    for pixel in matrix["pixels"]:
        spec = pixels[pixel["name"]]
        if category == "real" and spec["category"] != "real":
            continue
        if category == "integer" and spec["category"] != "integer":
            continue
        if png and not spec.get("png", False):
            continue
        for dim in matrix["dimensions"]:
            entries.append((spec["cxx"], dim, _enum_id(spec)))
    return entries


def render_builtin(matrix: dict, pixels: dict) -> str:
    all_entries = builtin_entries(matrix, pixels)
    real_entries = builtin_entries(matrix, pixels, category="real")
    integer_entries = builtin_entries(matrix, pixels, category="integer")
    png_entries = builtin_entries(matrix, pixels, png=True)
    pairs = []
    for left in matrix["pixels"]:
        for right in matrix["pixels"]:
            in_spec = pixels[left["name"]]
            out_spec = pixels[right["name"]]
            for dim in matrix["dimensions"]:
                pairs.append((in_spec["cxx"], out_spec["cxx"], dim, _enum_id(in_spec), _enum_id(out_spec)))

    def switch(entries, extra_true=False):
        if not entries:
            return "  return false;\n"
        ids = []
        seen = set()
        for _cxx, _dim, enum_id in entries:
            if enum_id not in seen:
                ids.append(enum_id)
                seen.add(enum_id)
        body = ["  switch (pixel)", "    {"]
        for enum_id in ids:
            dims = sorted({dim for _cxx, dim, enum in entries if enum == enum_id})
            test = " || ".join(f"dimension == {dim}" for dim in dims)
            body.append(f"    case {enum_id}:")
            body.append(f"      return {test};")
        body.append("    default:")
        body.append("      return false;")
        body.append("    }")
        return "\n".join(body) + "\n"

    parts = [
        f"/* {MARKER}. Do not edit. */",
        "#pragma once",
        "",
        "inline bool",
        "itklib_pixel_dim_built (itklib_pixel_id pixel, unsigned dimension)",
        "{",
        switch(all_entries).rstrip(),
        "}",
        "",
        "inline bool",
        "itklib_png_pixel (itklib_pixel_id pixel)",
        "{",
        switch([(cxx, 0, enum) for cxx, _dim, enum in png_entries]).replace(
            "dimension == 0", "true"
        ).rstrip() if png_entries else "  return false;",
        "}",
        "",
        _visit_function("itklib_visit_builtin", all_entries),
        _visit_function("itklib_visit_real", real_entries),
        _visit_function("itklib_visit_integer", integer_entries),
        _visit_function("itklib_visit_pair", pairs, pair=True),
    ]
    return "\n".join(parts).rstrip() + "\n"


def render_supported_cxx(filters: list[dict], matrix: dict, pixels: dict) -> str:
    lines = [
        f"/* {MARKER}. Do not edit. */",
        '#include "itklib_internal.hpp"',
        "",
        "extern \"C\" int",
        "itklib_filter_supported (int filter_id, int input_pixel, int output_pixel,",
        "                          unsigned dimension)",
        "{",
        "  const auto input = static_cast<itklib_pixel_id> (input_pixel);",
        "  const auto output = static_cast<itklib_pixel_id> (output_pixel);",
        "  switch (filter_id)",
        "    {",
    ]
    for filt in filters:
        pairs = instantiations(filt, matrix, pixels)
        lines.append(f"    case {int(filt['id'])}:")
        if filt.get("output") == "cast":
            lines.append(
                "      return itklib_pixel_dim_built (input, dimension)"
            )
            lines.append(
                "             && itklib_pixel_dim_built (output, dimension) ? 1 : 0;"
            )
            continue
        if not pairs:
            lines.append("      return 0;")
            continue
        grouped: dict[str, list[int]] = {}
        for kind, dim in pairs:
            grouped.setdefault(kind, []).append(dim)
        checks = []
        for kind, dims in grouped.items():
            spec = next(spec for spec in pixels.values() if spec["ada_kind"] == kind)
            dim_test = " || ".join(f"dimension == {dim}" for dim in sorted(set(dims)))
            checks.append(f"(input == {_enum_id(spec)} && ({dim_test}))")
        test = " || ".join(checks)
        lines.append(f"      if (input != output) {{ return 0; }}")
        lines.append(f"      return {test} ? 1 : 0;")
    lines += [
        "    default:",
        "      return 0;",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def render_filters_h(generated: list[dict]) -> str:
    lines = [
        f"/* {MARKER}. Do not edit. Included from inside extern \"C\" in itklib.h. */",
    ]
    for filt in generated:
        if filt["output"] == "none":
            lines.append(
                f"int {filt['c_prefix']}_new (itklib_pixel_id pixel, unsigned dimension,"
            )
            lines.append("    itklib_object ** out, itklib_error * error);")
        else:
            lines.append(
                f"int {filt['c_prefix']}_new (itklib_pixel_id input_pixel, itklib_pixel_id output_pixel,"
            )
            lines.append("    unsigned dimension, itklib_object ** out, itklib_error * error);")
        for member in filt["members"]:
            params = member["c_params"]
            lines.append(
                f"int {filt['c_prefix']}_{member['snake']} (itklib_object * filter{params}, itklib_error * error);"
            )
    lines.append("")
    return "\n".join(lines)


def render_classes(generated: list[dict]) -> str:
    known = {
        "ITKLIB_CLASS_IMAGE",
        "ITKLIB_CLASS_READER",
        "ITKLIB_CLASS_WRITER",
        "ITKLIB_CLASS_GAUSSIAN",
        "ITKLIB_CLASS_MEDIAN",
        "ITKLIB_CLASS_THRESHOLD",
        "ITKLIB_CLASS_RESCALE",
        "ITKLIB_CLASS_SHRINK",
        "ITKLIB_CLASS_RESAMPLE",
        "ITKLIB_CLASS_FLIP",
        "ITKLIB_CLASS_EXTRACT",
        "ITKLIB_CLASS_GRADIENT",
        "ITKLIB_CLASS_STATISTICS",
    }
    lines = [f"/* {MARKER}. Do not edit. */"]
    next_id = 100
    for filt in generated:
        klass = filt["klass"]
        if klass in known or not klass.startswith("ITKLIB_CLASS_"):
            continue
        lines.append(f"constexpr int {klass} = {next_id};")
        known.add(klass)
        next_id += 1
    if len(lines) == 1:
        lines.append("/* No generated class ids beyond the hand-written enum. */")
    lines.append("")
    return "\n".join(lines)


