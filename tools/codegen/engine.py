def render_test(generated: list[dict], matrix: dict, pixels: dict) -> str:
    lines = [
        f"--  {MARKER}. Do not edit.",
        "with Ada.Command_Line;",
        "with Ada.Text_IO;",
        "with Itklib.Supported;",
        "with Itklib.Instances.UInt16;",
    ]
    extra = []
    for pixel in matrix["pixels"]:
        spec = pixels[pixel["name"]]
        if spec.get("signature") == "hand":
            continue
        if spec["ada_kind"] == "UInt16":
            continue
        lines.append(f"with Itklib.Instances.{spec['ada_kind']};")
        lines.append("with Itklib.IO.Image_File_Writer;")
        extra.append(spec)
    lines += [
        "",
        "procedure Generated_Tests is",
        "   Failures : Natural := 0;",
        "",
        "   procedure Check (Condition : Boolean; Label : String) is",
        "   begin",
        "      if not Condition then",
        "         Ada.Text_IO.Put_Line (\"FAIL: \" & Label);",
        "         Failures := Failures + 1;",
        "      end if;",
        "   end Check;",
        "",
        "   procedure Test_Table is",
        "   begin",
        "      Check (Itklib.Supported.Image_Built (Itklib.UInt16, 2), \"uint16 2D image\");",
        "      Check (Itklib.Supported.Image_Built (Itklib.UInt16, 3), \"uint16 3D image\");",
        "      Check (not Itklib.Supported.Image_Built (Itklib.UInt16, 4), \"uint16 4D image\");",
        "      Check",
        "        (Itklib.Supported.Agrees",
        "           (Itklib.Supported.DiscreteGaussian, Itklib.UInt16, Itklib.UInt16, 2),",
        "         \"C table agrees for discrete gaussian\");",
    ]
    float_built = any(pixel["name"] == "float32" for pixel in matrix["pixels"])
    if not float_built:
        lines.append(
            "      Check (not Itklib.Supported.Image_Built (Itklib.Float32, 2), \"float32 stays generated-only\");"
        )
    else:
        lines.append(
            "      Check (Itklib.Supported.Image_Built (Itklib.Float32, 2), \"float32 2D image\");"
        )
        lines.append(
            "      Check (not Itklib.Supported.Png_Writer (Itklib.Float32, 2), \"float32 png writer\");"
        )
    lines += [
        "   end Test_Table;",
        "",
        "   procedure Test_Gaussian is",
        "      package Img renames Itklib.Instances.UInt16.Image_2D;",
        "      package Smooth renames Itklib.Instances.UInt16.DiscreteGaussian_2D;",
        "      Source : Img.Image := Img.Create ([4, 4]);",
        "      Filter : Smooth.Filter := Smooth.Create;",
        "",
        "      procedure Paint (Data : in out Img.Pixel_Array) is",
        "      begin",
        "         for Item of Data loop",
        "            Item := 80;",
        "         end loop;",
        "      end Paint;",
        "",
        "      procedure Apply_Paint is new Img.With_Buffer (Paint);",
        "",
        "      function Near_Center return Boolean is",
        "         Match : Boolean := True;",
        "         Result : Img.Image := Smooth.Get_Output (Filter);",
        "",
        "         procedure Read (Data : in out Img.Pixel_Array) is",
        "         begin",
        "            for Item of Data loop",
        "               if Item not in 78 .. 82 then",
        "                  Match := False;",
        "                  return;",
        "               end if;",
        "            end loop;",
        "         end Read;",
        "",
        "         procedure Apply is new Img.With_Buffer (Read);",
        "      begin",
        "         Apply (Result);",
        "         return Match;",
        "      end Near_Center;",
        "   begin",
        "      Apply_Paint (Source);",
        "      Filter.Set_Input (Source);",
        "      Filter.Set_Variance ([1.0, 1.0]);",
        "      Filter.Set_Maximum_Error ([0.1, 0.1]);",
        "      Filter.Set_Use_Image_Spacing (False);",
        "      Filter.Update;",
        "      Check (Near_Center, \"generated discrete gaussian on a constant image\");",
        "   end Test_Gaussian;",
        "",
    ]
    if float_built:
        lines += [
            "   procedure Test_Float32 is",
            "      package Img renames Itklib.Instances.Float32.Image_2D;",
            "      package Smooth renames Itklib.Instances.Float32.DiscreteGaussian_2D;",
            "      Source : Img.Image := Img.Create ([4, 4]);",
            "      Filter : Smooth.Filter := Smooth.Create;",
            "",
            "      procedure Paint (Data : in out Img.Pixel_Array) is",
            "      begin",
            "         for Item of Data loop",
            "            Item := 1.5;",
            "         end loop;",
            "      end Paint;",
            "",
            "      procedure Apply_Paint is new Img.With_Buffer (Paint);",
            "",
            "      procedure Reject_Writer is",
            "         package Writer is new Itklib.IO.Image_File_Writer (Img);",
            "         Unused : Writer.Filter := Writer.Create;",
            "      begin",
            "         Check (Writer.Reference_Count (Unused) = 0, \"unreachable writer\");",
            "      end Reject_Writer;",
            "   begin",
            "      Apply_Paint (Source);",
            "      Filter.Set_Input (Source);",
            "      Filter.Set_Variance ([0.5, 0.5]);",
            "      Filter.Set_Use_Image_Spacing (False);",
            "      Filter.Update;",
            "      declare",
            "         Result : Img.Image := Filter.Get_Output;",
            "      begin",
            "         Check (Img.Reference_Count (Result) > 0, \"float32 gaussian output\");",
            "      end;",
            "      begin",
            "         Reject_Writer;",
            "         Check (False, \"float32 PNG writer should be rejected\");",
            "      exception",
            "         when Itklib.Unsupported_Instantiation =>",
            "            null;",
            "      end;",
            "   end Test_Float32;",
            "",
        ]
    lines += [
        "begin",
        "   Test_Table;",
        "   Test_Gaussian;",
    ]
    if float_built:
        lines.append("   Test_Float32;")
    lines += [
        "   if Failures /= 0 then",
        "      Ada.Command_Line.Set_Exit_Status (Ada.Command_Line.Failure);",
        "   end if;",
        "end Generated_Tests;",
        "",
    ]
    return "\n".join(lines)


def render_golden_hooks(filters: list[dict]) -> str:
    lines = [
        f"# {MARKER}. Do not edit.",
        "# SimpleITK (Apache-2.0) is the oracle. Each row is the adaimg hook a",
        "# generated or hand-written filter contributes. tools/golden_compare.py",
        "# still runs the pixel comparison for the options it lists.",
        "HOOKS = (",
    ]
    for filt in filters:
        option = (filt.get("adaimg") or {}).get("option", "")
        help_text = (filt.get("adaimg") or {}).get("help", "")
        lines.append(
            f"    {{'filter': '{filt['name']}', 'option': '{option}', 'help': {help_text!r}}},"
        )
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def render_cmake(sources: list[str]) -> str:
    body = "\n".join(f"  {path}" for path in sources)
    return (
        "cmake_minimum_required(VERSION 3.16)\n"
        "# Generated-source inventory. GPRbuild is the supported build of the shim.\n"
        "# tools/generate.py rewrites the list between the markers.\n"
        "set(ITKLIB_GENERATED_SOURCES\n"
        "# BEGIN GENERATED\n"
        f"{body}\n"
        "# END GENERATED\n"
        ")\n"
    )


def render_gpr_block(paths: list[str]) -> str:
    lines = ["   -- BEGIN GENERATED SOURCES"]
    for path in paths:
        lines.append(f"   -- {path}")
    lines.append("   -- END GENERATED SOURCES")
    return "\n".join(lines)


def parents_needed(units: list[str], root: Path) -> dict[str, str]:
    files = {}
    for unit in units:
        parts = unit.split(".")
        for index in range(2, len(parts)):
            parent = ".".join(parts[:index])
            filename = unit_file(parent, ".ads")
            if (root / "src" / "ada" / filename).exists():
                continue
            rel = f"src/ada/generated/{filename}"
            if rel not in files:
                files[rel] = (
                    f"--  {MARKER}. Do not edit.\n"
                    f"package {parent} with SPARK_Mode => Off is\n"
                    "end " + parent + ";\n"
                )
    return files


def build_plan(root: Path = ROOT, matrix: dict | None = None) -> dict[str, str]:
    matrix = matrix if matrix is not None else load_matrix(root)
    pixels = pixel_db(root)
    filters = [prepare_filter(item) for item in load_filters(root)]
    env = Environment(
        loader=FileSystemLoader(str(TEMPLATES)),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    plan: dict[str, str] = {}
    generated = [filt for filt in filters if filt.get("generate_sources")]
    for filt in generated:
        cxx = env.get_template("filter.cxx.j2").render(**filt)
        ads = env.get_template("filter.ads.j2").render(**filt)
        adb = env.get_template("filter.adb.j2").render(**filt)
        plan[f"shim/generated/{filt['snake']}.cxx"] = cxx
        plan[f"src/ada/generated/{unit_file(filt['ada_package'], '.ads')}"] = ads
        plan[f"src/ada/generated/{unit_file(filt['ada_package'], '.adb')}"] = adb
    plan.update(parents_needed([filt["ada_package"] for filt in generated], root))
    if "src/ada/generated/itklib-instances.ads" not in plan:
        plan["src/ada/generated/itklib-instances.ads"] = (
            f"--  {MARKER}. Do not edit.\n"
            "package Itklib.Instances with SPARK_Mode => Off is\n"
            "   --  One child per pixel in tools/matrix.yaml.\n"
            "end Itklib.Instances;\n"
        )
    spec, body = render_supported_ada(filters, matrix, pixels)
    plan["src/ada/generated/itklib-supported.ads"] = spec
    plan["src/ada/generated/itklib-supported.adb"] = body
    thin_spec, thin_body = render_thin(generated)
    plan["src/ada/generated/itklib-thin-generated.ads"] = thin_spec
    plan["src/ada/generated/itklib-thin-generated.adb"] = thin_body
    for pixel in matrix["pixels"]:
        spec_pixel = pixels[pixel["name"]]
        if spec_pixel.get("signature") == "hand":
            continue
        plan[f"src/ada/generated/{unit_file('Itklib.Pixels.' + spec_pixel['ada_kind'], '.ads')}"] = (
            render_pixel_package(spec_pixel)
        )
        plan[f"src/ada/generated/{unit_file('Itklib.Instances.' + spec_pixel['ada_kind'], '.ads')}"] = (
            render_instances(pixel, spec_pixel, filters, matrix, pixels)
        )
    # UInt16 instances are generated even though the signature package is hand-written.
    uint16 = pixels["uint16"]
    uint16_pixel = next(pixel for pixel in matrix["pixels"] if pixel["name"] == "uint16")
    plan["src/ada/generated/itklib-instances-uint16.ads"] = render_instances(
        uint16_pixel, uint16, filters, matrix, pixels
    )
    plan["shim/generated/itklib_builtin.hpp"] = render_builtin(matrix, pixels)
    plan["shim/generated/itklib_supported.cxx"] = render_supported_cxx(filters, matrix, pixels)
    plan["shim/generated/itklib_filters.h"] = render_filters_h(generated)
    plan["shim/generated/itklib_classes.inc"] = render_classes(generated)
    plan["tests/generated/generated_tests.adb"] = render_test(generated, matrix, pixels)
    plan["tools/generated/golden_hooks.py"] = render_golden_hooks(filters)
    cxx_sources = ["generated/itklib_supported.cxx"] + [
        f"generated/{filt['snake']}.cxx" for filt in generated
    ]
    plan["shim/CMakeLists.txt"] = render_cmake(cxx_sources)
    return plan


def gpr_with_block(root: Path, paths: list[str]) -> str:
    text = (root / "itklib.gpr").read_text()
    begin = "   -- BEGIN GENERATED SOURCES"
    end = "   -- END GENERATED SOURCES"
    if begin not in text or end not in text:
        raise SystemExit("itklib.gpr is missing generated-source markers")
    block = render_gpr_block(paths)
    start = text.index(begin)
    finish = text.index(end) + len(end)
    return text[:start] + block + text[finish:]


def apply_plan(plan: dict[str, str], root: Path = ROOT) -> list[str]:
    changed = []
    for rel, content in sorted(plan.items()):
        if rel == "itklib.gpr":
            continue
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        current = path.read_text() if path.exists() else None
        if current != content:
            path.write_text(content)
            changed.append(rel)
    listed = sorted(
        rel for rel in plan
        if rel.startswith("src/ada/generated/") or rel.startswith("shim/generated/")
    )
    gpr = gpr_with_block(root, listed)
    gpr_path = root / "itklib.gpr"
    if gpr_path.read_text() != gpr:
        gpr_path.write_text(gpr)
        changed.append("itklib.gpr")
    removed = sweep(plan, root)
    changed.extend(removed)
    return changed


def sweep(plan: dict[str, str], root: Path) -> list[str]:
    removed = []
    planned = {root / rel for rel in plan}
    for directory in MANAGED_DIRS:
        folder = root / directory
        if not folder.exists():
            continue
        for path in folder.rglob("*"):
            if not path.is_file() or path.name == ".gitkeep":
                continue
            if path in planned or path.resolve() in {item.resolve() for item in planned}:
                continue
            text = path.read_text(errors="ignore")[:500]
            if MARKER in text:
                path.unlink()
                removed.append(str(path.relative_to(root)))
    return removed


def diff_plan(plan: dict[str, str], root: Path = ROOT) -> str:
    chunks = []
    for rel, content in sorted(plan.items()):
        path = root / rel
        current = path.read_text() if path.exists() else ""
        if current == content:
            continue
        chunks.append(f"--- {rel}\n+++ {rel}\n")
        # A short unified-style summary is enough for --diff; callers that
        # need a precise patch can regenerate.
        import difflib
        chunks.append(
            "".join(
                difflib.unified_diff(
                    current.splitlines(keepends=True),
                    content.splitlines(keepends=True),
                    fromfile=rel,
                    tofile=rel,
                )
            )
        )
    gpr = gpr_with_block(root, sorted(
        rel for rel in plan
        if rel.startswith("src/ada/generated/") or rel.startswith("shim/generated/")
    ))
    current = (root / "itklib.gpr").read_text()
    if current != gpr:
        import difflib
        chunks.append(
            "".join(
                difflib.unified_diff(
                    current.splitlines(keepends=True),
                    gpr.splitlines(keepends=True),
                    fromfile="itklib.gpr",
                    tofile="itklib.gpr",
                )
            )
        )
    return "".join(chunks)


def _cxx_compiler() -> str:
    chosen = os.environ.get("CXX", "")
    if chosen:
        return chosen
    completed = subprocess.run(
        ["alr", "exec", "--", "which", "g++"],
        capture_output=True,
        text=True,
    )
    if completed.returncode == 0 and completed.stdout.strip():
        return completed.stdout.strip()
    return "g++"


def try_compile(spec: dict, dims: list[int], root: Path = ROOT) -> None:
    itk_dir = os.environ.get("ITK_DIR", "")
    if not itk_dir:
        default = Path("/opt/itk-5.4.8/lib/cmake/ITK-5.4")
        if default.is_dir():
            itk_dir = str(default)
    if not itk_dir:
        raise SystemExit("ITK_DIR is not set; refusing to write files without try_compile")
    with tempfile.TemporaryDirectory(prefix="itklib-pixel-") as folder:
        src = Path(folder)
        instances = "\n".join(
            f"template class itk::Image<{spec['cxx']}, {dim}>;" for dim in dims
        )
        (src / "probe.cpp").write_text(
            "#include \"itkImage.h\"\n"
            "#include <cstdint>\n"
            f"{instances}\n"
            "int main() { return 0; }\n"
        )
        (src / "CMakeLists.txt").write_text(
            "cmake_minimum_required(VERSION 3.16)\n"
            "project(itklib_pixel_probe CXX)\n"
            "find_package(ITK 5.4.8 REQUIRED)\n"
            "include(${ITK_USE_FILE})\n"
            "add_executable(probe probe.cpp)\n"
            "target_link_libraries(probe ${ITK_LIBRARIES})\n"
        )
        cxx = _cxx_compiler()
        configure = subprocess.run(
            [
                "cmake",
                "-S",
                str(src),
                "-B",
                str(src / "build"),
                f"-DITK_DIR={itk_dir}",
                f"-DCMAKE_CXX_COMPILER={cxx}",
            ],
            capture_output=True,
            text=True,
        )
        if configure.returncode != 0:
            raise SystemExit(
                "ITK try_compile failed to configure:\n" + configure.stderr[-2000:]
            )
        build = subprocess.run(
            ["cmake", "--build", str(src / "build")],
            capture_output=True,
            text=True,
        )
        if build.returncode != 0:
            raise SystemExit("ITK try_compile failed to build:\n" + build.stderr[-2000:])


def modules_missing(filters: list[dict], root: Path = ROOT) -> list[str]:
    text = (root / "tools" / "itk_modules.txt").read_text()
    enabled = set()
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            enabled.add(line)
    missing = []
    for filt in filters:
        module = filt.get("module")
        if filt.get("generate_sources") and module and module not in enabled:
            missing.append(f"{filt['name']} needs {module}")
    return missing
